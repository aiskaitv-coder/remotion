import re
def clean(t): return re.sub(r'\s+', ' ', re.sub(r'\[[a-z]+\]', '', t)).strip()
def words(t): return len([w for w in clean(t).split(' ') if re.search(r'\w', w)])
def rows():
    return [{"scene": s, "vo_a": a, "vo_b": clean(a), "words": words(a), "vo_seconds": round(words(a)/145*60, 2)} for s, a in VO]
if __name__ == '__main__':
    r = rows(); tot = sum(x['words'] for x in r)
    print('TOTAL', tot, 'words', round(tot/145*60, 1), 's'); [print(x['scene'], x['words'], x['vo_seconds']) for x in r]
